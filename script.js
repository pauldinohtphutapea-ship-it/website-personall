/* ===== MEMBANGUN ISI HALAMAN MATERI DENGAN AMAN ===== */
const params = new URLSearchParams(window.location.search);
const requestedMaterial = params.get("materi");

const profilePage = document.getElementById("profilePage");
const detailPage = document.getElementById("detailPage");
const detailContent = document.getElementById("detailContent");

function addTextElement(parent, tagName, text, className = "") {
    const element = document.createElement(tagName);
    element.textContent = text;

    if (className) {
        element.className = className;
    }

    parent.appendChild(element);
    return element;
}

function renderSection(parent, section) {
    addTextElement(parent, "h2", section.heading);

    if (section.paragraphs) {
        section.paragraphs.forEach(text => {
            addTextElement(parent, "p", text);
        });
    }

    if (section.bullets) {
        const list = document.createElement("ul");

        section.bullets.forEach(text => {
            addTextElement(list, "li", text);
        });

        parent.appendChild(list);
    }

    if (section.paragraphsAfter) {
        section.paragraphsAfter.forEach(text => {
            addTextElement(parent, "p", text);
        });
    }

    if (section.subsections) {
        section.subsections.forEach(subsection => {
            renderSection(parent, subsection);
        });
    }
}

if (requestedMaterial !== null && profilePage && detailPage && detailContent) {
    const selectedMaterial = Number(requestedMaterial);
    const material = Number.isInteger(selectedMaterial)
        ? materials[selectedMaterial - 1]
        : null;

    profilePage.hidden = true;
    detailPage.hidden = false;

    if (material) {
        document.title = `${material.title} - ${material.subtitle} | Paul Dino`;

        addTextElement(detailContent, "p", "TREN TEKNOLOGI INFORMASI", "eyebrow");
        addTextElement(detailContent, "h1", material.title);
        addTextElement(detailContent, "p", material.subtitle, "detail-subtitle");

        material.sections.forEach(section => {
            renderSection(detailContent, section);
        });

        const navigation = document.createElement("div");
        navigation.className = "material-navigation";

        if (selectedMaterial > 1) {
            const previous = document.createElement("a");
            previous.className = "material-nav-link";
            previous.href = `index.html?materi=${selectedMaterial - 1}`;
            previous.textContent = "← Materi Sebelumnya";
            navigation.appendChild(previous);
        }

        if (selectedMaterial < materials.length) {
            const next = document.createElement("a");
            next.className = "material-nav-link";
            next.href = `index.html?materi=${selectedMaterial + 1}`;
            next.textContent = "Materi Selanjutnya →";
            navigation.appendChild(next);
        }

        detailContent.appendChild(navigation);
    } else {
        addTextElement(detailContent, "h1", "Materi tidak ditemukan");
        addTextElement(
            detailContent,
            "p",
            "Materi yang kamu cari tidak tersedia. Silakan kembali ke halaman profil."
        );
    }
}